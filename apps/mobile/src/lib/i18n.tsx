const DICTS: Record<Locale, typeof ar> = { ar, en }

type I18nValue = {
  locale: Locale
  t: typeof ar
  isRTL: boolean
  setLocale: (l: Locale) => Promise<void>
}

const I18nContext = createContext<I18nValue | null>(null)

/** Arabic-first: the app defaults to ar/RTL; the choice persists on-device. */
export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("ar")

  useEffect(() => {
    readPlatformStorage(LOCALE_KEY)
      .then((saved) => {
        if (saved === "en" || saved === "ar") setLocaleState(saved)
      })
      .catch(() => undefined)
  }, [])

  const setLocale = useCallback(async (l: Locale) => {
    setLocaleState(l)
    await writePlatformStorage(LOCALE_KEY, l).catch(() => undefined)
  }, [])

  const value = useMemo<I18nValue>(
    () => ({ locale, t: DICTS[locale], isRTL: locale === "ar", setLocale }),
    [locale, setLocale],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error("useI18n must be used within I18nProvider")
  return ctx
}
